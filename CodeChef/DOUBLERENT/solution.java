import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef {
    public static void main (String[] args) throws java.lang.Exception {
        Scanner scanner = new Scanner(System.in);
        
        if (scanner.hasNextInt()) {
            int x = scanner.nextInt();
            System.out.println(x * 2);
        }
        
        scanner.close();
    }
}
